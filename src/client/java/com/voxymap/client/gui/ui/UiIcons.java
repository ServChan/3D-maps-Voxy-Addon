    private UiIcons() {
    }

    static int[][] encode(String[] rows) {
        if (rows.length != UiTheme.ICON_SIZE) {
            throw new IllegalArgumentException("Icon must have " + UiTheme.ICON_SIZE + " rows");
        }
        List<int[]> runs = new ArrayList<>();
        for (int y = 0; y < rows.length; y++) {
            String row = rows[y];
            if (row.length() != UiTheme.ICON_SIZE) {
                throw new IllegalArgumentException("Icon row " + y + " must have " + UiTheme.ICON_SIZE + " columns");
            }
            int start = -1;
            for (int x = 0; x <= row.length(); x++) {
                boolean filled = x < row.length() && row.charAt(x) == '#';
                if (filled && start < 0) {
                    start = x;
                } else if (!filled && start >= 0) {
                    runs.add(new int[]{start, y, x - start});
                    start = -1;
                }
            }
        }
        return runs.toArray(new int[0][]);
    }

    public static void draw(GuiGraphicsExtractor g, Icon icon, int x, int y, int color) {
        for (int[] run : icon.runs()) {
            g.fill(x + run[0], y + run[1], x + run[0] + run[2], y + run[1] + 1, color);
        }
    }

    public static void drawCentered(GuiGraphicsExtractor g, Icon icon, int centerX, int centerY, int color) {
        draw(g, icon, centerX - UiTheme.ICON_SIZE / 2, centerY - UiTheme.ICON_SIZE / 2, color);
    }
